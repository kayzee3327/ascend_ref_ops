"""The two KDA operators from ops-transformer, under renamed op types.

Unlike the fla arm, there is nothing to install: the toolkit here is CANN 9.0.0
and neither operator exists in it -- ``libopapi.so`` has no ``aclnnChunkKdaFwd``
and no kernel binary -- so both are compiled from the pinned 9.2.0 sources as
custom vendor packages by ``python -m ref_ops.build``.

Those packages are **renamed copies**. ``RefOpsCannChunkKdaFwd`` and
``RefOpsCannRecurrentKda`` are the same kernels under different op types, which
is what lets them sit alongside fla's identically-named originals in one
process. ``ref_ops/__init__.py`` puts both vendor roots on the dlsym search
path; see ``pins.py`` for why four identifiers have to move together for a
rename to be real.

The two operators are bound differently, because upstream binds them
differently:

``chunk_kda``      no ``torch_extension/`` wrapper exists upstream, so this
                   module compiles its own aclnn bridge -- a small C++ file
                   calling ``ACLNN_CMD``, JIT-built through ops-transformer's
                   own ``OpBuilder`` so the include and link ordering is the
                   repo's rather than guessed (notably: CANN headers must
                   precede torch_npu's older vendored copies).
``recurrent_kda``  a wrapper does exist, but only becomes importable once the
                   vendor-named wheel installs it, which ``build.py`` does.

A missing build is reported, not raised, by ``available()``: a caller probing
the four arms gets a one-line reason it can print next to a skipped column.
Calling either operator without the build raises, which is what an arm probe
turns into that skipped column.
"""

from __future__ import annotations

import functools
import os
import subprocess
from pathlib import Path
from typing import Any, Optional

from . import OPP_ROOT
from .pins import OPS_BY_SNAKE, Op

__all__ = ["chunk_kda", "recurrent_kda", "available", "load"]

_HINT = "run `python -m ref_ops.build` first"

# Where the JIT-compiled bridge is cached. Inside the package, like everything
# else this project builds.
_BUILD_DIR = Path(__file__).resolve().parent / "_bridge"


def _vendor_dir(op: Op) -> Path:
    return OPP_ROOT / "vendors" / f"{op.vendor}_transformer"


def _exports(lib: Path, symbol: str) -> bool:
    """Whether ``lib`` defines ``symbol``."""
    try:
        out = subprocess.run(
            ["nm", "-D", "--defined-only", str(lib)],
            capture_output=True, text=True, check=False,
        ).stdout
    except OSError:
        # No nm: assume it is the right library and let dlsym report the truth.
        return True
    return any(
        line.split()[-1] == symbol for line in out.splitlines() if symbol in line
    )


def available(name: str = "chunk_kda_fwd") -> tuple[bool, str]:
    """Whether op ``name``'s vendor package is installed, and why not if it is not.

    Checks for the operator's own ``aclnn`` symbol rather than settling for a
    vendor directory that holds a ``libcust_opapi.so``. The sibling op's package
    satisfies both of those, and a first-match-wins dlsym scan then picks the
    wrong package -- the op looks available and fails at the first launch with
    "not in libopapi.so".
    """
    op = OPS_BY_SNAKE[name]
    vendor = _vendor_dir(op)
    lib = vendor / "op_api" / "lib" / "libcust_opapi.so"
    if not lib.is_file():
        return False, f"{op.renamed_snake}: no vendor package at {vendor}; {_HINT}"
    if not _exports(lib, op.aclnn):
        return False, f"{lib} exports no {op.aclnn}; {_HINT}"
    if op.needs_wheel and not _wheel_installed(op):
        return False, (
            f"{op.renamed_snake}: the vendor package is installed but "
            f"{_wheel_package(op)} is not importable; {_HINT}"
        )
    return True, ""


def _wheel_package(op: Op) -> str:
    """The vendor-suffixed wheel that carries this op's Python entry point.

    ``setup.py`` suffixes the package name whenever ``TORCH_EXTENSION_OPS`` is
    set, which the per-op build always sets -- so plain ``cann_ops_transformer``
    is never what gets installed.
    """
    return f"cann_ops_transformer_{op.vendor}"


def _wheel_installed(op: Op) -> bool:
    import importlib.util

    return importlib.util.find_spec(_wheel_package(op)) is not None


# --- chunk_kda: the bridge upstream does not ship ------------------------

_BRIDGE_TEMPLATE = r"""
// Torch bridge for aclnn{CAMEL}, which upstream ships no wrapper for.
// Generated by ref_ops/cann.py against the renamed op type; the only thing
// this file knows about the rename is the aclnn symbol name.
#include <string>
#include <tuple>
#include <vector>

#include <torch/extension.h>

#include "aclnn_common.h"

namespace op_api {{

// Only the outputs a forward measurement reads are requested. The optional
// ones (gk, w, u, qg, kg, v_new, h) are passed as undefined tensors, which the
// L2 interface treats as "do not export". Aqk and Akk are not optional and are
// allocated and written regardless -- that cost is part of what this kernel
// does and belongs in any measurement of it.
std::tuple<at::Tensor, at::Tensor> chunk_kda(
    const at::Tensor &q, const at::Tensor &k, const at::Tensor &v,
    const at::Tensor &g, const at::Tensor &beta,
    const c10::optional<at::Tensor> &aLog,
    const c10::optional<at::Tensor> &dtBias,
    const c10::optional<at::Tensor> &initialState,
    const c10::optional<at::Tensor> &cuSeqlens,
    std::string layout, double scale, int64_t chunkSize,
    bool safeGate, double lowerBound, bool useGateInKernel, bool stateVFirst)
{{
    TORCH_CHECK(q.dim() == 3, "ref_ops.cann.chunk_kda expects TND inputs");
    const int64_t T = q.size(0);
    const int64_t K = q.size(2);
    const int64_t HV = v.size(1);
    const int64_t V = v.size(2);
    const int64_t C = chunkSize;

    // One logical sequence per cu_seqlens interval.
    TORCH_CHECK(cuSeqlens.has_value(), "ref_ops.cann.chunk_kda requires cu_seqlens");
    const at::Tensor cu = cuSeqlens.value().to(at::kCPU).to(at::kLong);
    const int64_t N = cu.numel() - 1;
    const int64_t *cuData = cu.data_ptr<int64_t>();

    // cu_seqlens crosses as an aclIntArray, not a tensor, so it must be a
    // host-side buffer that outlives the call below.
    const std::vector<int64_t> cuVec(cuData, cuData + cu.numel());
    const at::IntArrayRef cuRef(cuVec);

    auto optsIn = q.options();
    auto optsF32 = q.options().dtype(at::kFloat);

    at::Tensor attnOut = at::empty({{T, HV, V}}, optsIn);
    at::Tensor finalState = stateVFirst
        ? at::empty({{N, HV, V, K}}, optsF32)
        : at::empty({{N, HV, K, V}}, optsF32);
    // Mandatory outputs, head-major.
    at::Tensor aqk = at::empty({{HV, T, C}}, optsIn);
    at::Tensor akk = at::empty({{HV, T, C}}, optsIn);

    // An undefined tensor converts to a null aclTensor*, which is how the L2
    // interface is told to skip an optional output. An empty optional does the
    // same for chunk_indices, which the op derives from cu_seqlens when absent.
    const at::Tensor none;
    const c10::optional<at::IntArrayRef> noChunkIndices = c10::nullopt;

    ACLNN_CMD(aclnn{CAMEL}, q, k, v, g, beta, aLog, dtBias, initialState,
              cuRef, noChunkIndices, layout, scale, chunkSize,
              safeGate, lowerBound, useGateInKernel, stateVFirst,
              attnOut, finalState, /*gkOut=*/none, aqk, akk,
              /*wOut=*/none, /*uOut=*/none, /*qgOut=*/none, /*kgOut=*/none,
              /*vNewOut=*/none, /*hOut=*/none);

    return std::make_tuple(attnOut, finalState);
}}

}} // namespace op_api

PYBIND11_MODULE(TORCH_EXTENSION_NAME, m)
{{
    m.def("chunk_kda", &op_api::chunk_kda, "aclnn{CAMEL} (TND)");
}}
"""


def _source_root() -> Path:
    """The extracted, renamed ops-transformer tree ``build.py`` wrote.

    Needed for ``OpBuilder`` and ``aclnn_common.h``. Recorded in the manifest
    rather than guessed, so the bridge is built against the same sources the
    vendor package was.
    """
    from . import manifest

    recorded = manifest().get("cann_source_root")
    if recorded:
        path = Path(recorded)
        if path.is_dir():
            return path
    raise RuntimeError(
        f"ref_ops.cann: no extracted ops-transformer tree recorded in the "
        f"manifest; {_HINT}"
    )


def _expose_source_tree() -> None:
    """Put the extracted ``torch_extension/`` on ``sys.path``, once.

    Both arms need it: the bridge arm imports ``OpBuilder`` from it, and the
    wheel arm needs the unsuffixed ``cann_ops_transformer`` package its own
    builder lazily imports.
    """
    import logging
    import sys

    # Importing the source-tree package for `OpBuilder` alone also runs its
    # `ops/__init__.py`, which tries to alias every operator in the repo to its
    # legacy module name and warns once per failure. A two-op extraction
    # contains none of those modules and wants none of them. Raised to ERROR
    # rather than silenced, so a real failure still prints.
    logging.getLogger("cann_ops_transformer.ops").setLevel(logging.ERROR)

    extension_dir = str(_source_root() / "torch_extension")
    if extension_dir not in sys.path:
        sys.path.insert(0, extension_dir)


@functools.lru_cache(maxsize=1)
def _load_bridge(op: Op):
    """JIT-compile the bridge against the repo's headers and the vendor libs.

    ``OpBuilder`` is used only for its include and link paths. Getting those
    right by hand is the fiddly part and the repo already encodes the ordering
    constraints, so this borrows them rather than restating them.
    """
    import torch_npu  # noqa: F401
    from torch.utils.cpp_extension import load

    _expose_source_tree()
    from cann_ops_transformer.op_builder import OpBuilder

    class _Bridge(OpBuilder):
        """``OpBuilder`` with every abstract hook declined.

        Nothing here registers a torch schema or a meta kernel: the bridge is
        reached as a plain pybind function, not through ``torch.ops``.
        """

        def __init__(self):
            super().__init__(op.renamed_snake, category=None)

        def sources(self):
            return []

        def schema(self):
            return None

        def register_meta(self):
            return None

    builder = _Bridge()
    builder.ensure_initialized()

    _BUILD_DIR.mkdir(exist_ok=True)
    text = _BRIDGE_TEMPLATE.format(CAMEL=op.renamed_camel)
    source = _BUILD_DIR / f"{op.renamed_snake}_bridge.cpp"
    if not source.is_file() or source.read_text() != text:
        source.write_text(text)

    return load(
        name=f"{op.renamed_snake}_bridge",
        sources=[str(source)],
        extra_include_paths=builder.include_paths(),
        extra_cflags=builder.cxx_args(),
        extra_ldflags=builder.extra_ldflags(),
        build_directory=str(_BUILD_DIR),
        verbose=False,
    )


@functools.lru_cache(maxsize=None)
def load(name: str) -> tuple[Optional[Any], Optional[str]]:
    """``(callable, None)`` for op ``name``, or ``(None, reason)`` if absent.

    Cached, and not just for tidiness: ``available`` shells out to ``nm``, so an
    uncached call from inside a benchmark's timed loop adds a flat,
    shape-independent ~68 ms to every measurement.
    """
    op = OPS_BY_SNAKE[name]
    ok, why = available(name)
    if not ok:
        return None, why

    if op.needs_wheel:
        import importlib

        # The vendor wheel is self-contained for everything except one lazy
        # import: its `OpBuilder.load` reaches for
        # `cann_ops_transformer.utils.arg_check` -- the *unsuffixed* package,
        # which is not what `setup.py` installed and is therefore not
        # importable. The extracted source tree has it, so put that on the
        # path. The failure without this is deferred to the first call, as
        # `ModuleNotFoundError: No module named 'cann_ops_transformer'` from
        # inside a torch op, which does not look like a packaging problem.
        _expose_source_tree()

        try:
            module = importlib.import_module(f"{_wheel_package(op)}.ops.attention")
        except ImportError as exc:
            return None, f"importing {_wheel_package(op)} failed: {exc}"
        fn = getattr(module, op.renamed_snake, None)
        if fn is None:
            return None, (
                f"{_wheel_package(op)} exposes no {op.renamed_snake}; {_HINT}"
            )
        return fn, None

    try:
        module = _load_bridge(op)
    except Exception as exc:  # the bridge compile, which has its own failures
        return None, f"building the {op.renamed_snake} torch bridge failed: {exc}"
    return module.chunk_kda, None


def chunk_kda(
    q,
    k,
    v,
    g,
    beta,
    *,
    scale: float,
    chunk_size: int,
    cu_seqlens,
    A_log=None,
    dt_bias=None,
    initial_state=None,
    safe_gate: bool = True,
    lower_bound: float = -5.0,
    use_gate_in_kernel: bool = True,
    state_v_first: bool = False,
):
    """``(attn_out, final_state)`` from ``RefOpsCannChunkKdaFwd``, TND input.

    ``attn_out`` is ``[T, HV, V]`` in the input dtype, ``final_state`` is fp32
    ``[N, HV, K, V]`` -- or ``[N, HV, V, K]`` with ``state_v_first``.

    ``cu_seqlens`` is a device tensor, int32 or int64; it is read on the host
    here because the op takes the offsets as an ``aclIntArray``, not a tensor.
    """
    op, why = load("chunk_kda_fwd")
    if op is None:
        raise RuntimeError(why)
    return op(
        q, k, v, g, beta, A_log, dt_bias, initial_state, cu_seqlens,
        "TND", float(scale), int(chunk_size),
        bool(safe_gate), float(lower_bound), bool(use_gate_in_kernel),
        bool(state_v_first),
    )


def recurrent_kda(*args: Any, **kwargs: Any):
    """``RefOpsCannRecurrentKda``, through its vendor wheel's entry point.

    Upstream's signature, forwarded as-is:

        recurrent_kda(q, k, v, g, beta, initial_state, *, cu_seqlens=None,
                      ssm_state_indices=None, A_log=None, dt_bias=None,
                      num_accepted_tokens=None, layout="BSND", scale=None, ...)

    Three things about this operator decide whether a number read out of it
    means anything, none of them fixable here:

    * **It is a decode/MTP kernel, capped at 8 tokens per sequence**
      (``MAX_MTP``), and it does not reject longer input: ``ValidateCuSeqlens``
      fails and ``Process`` returns *without writing anything*, as a successful
      aclnn call. So a prefill-shaped comparison against it measures whatever
      was in the output allocation.
    * ``layout="TND"`` for a packed sequence; ``BSND`` reads a squeezed
      ``[1,T,H,D]``'s ``T`` as the batch.
    * ``ssm_state_indices`` is per *token* in TND, so per-sequence pool indices
      need ``repeat_interleave(lengths)``.

    It mutates ``initial_state`` in place unless ``inplace_final_state=False``.
    """
    op, why = load("recurrent_kda")
    if op is None:
        raise RuntimeError(why)
    return op(*args, **kwargs)
